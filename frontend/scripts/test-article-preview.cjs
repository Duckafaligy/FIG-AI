const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const source = fs.readFileSync(path.join(__dirname, '../components/library-article-preview.tsx'), 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { jsx: ts.JsxEmit.ReactJSX, module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const exportsObject = {};
vm.runInNewContext(code, { exports: exportsObject, require });
const render = props => renderToStaticMarkup(React.createElement(exportsObject.ArticlePreview, { title: 'Test article', body: '', category: 'blog', hostname: 'example.com', mobile: false, ...props }));
assert.match(render({}), /Your article body will appear/);
const markup = render({ body: '## Heading\n\nA paragraph.\n\n- First\n- Second\n\n> Quote\n\n<script>alert(1)</script>' });
assert.match(markup, /<h2>Heading<\/h2>/);
assert.match(markup, /<ul><li>First<\/li><li>Second<\/li><\/ul>/);
assert.match(markup, /<blockquote>Quote<\/blockquote>/);
assert.ok(!markup.includes('<script>'));
assert.match(markup, /&lt;script&gt;/);
assert.match(render({ mobile: true }), /cms-preview-mobile/);
console.log('Article preview checks passed: empty state, headings, lists, quotes, escaped HTML, mobile mode.');
